# Global scrape semaphore to prevent machine-gun burst traffic
_SCRAPE_SEMAPHORE = asyncio.Semaphore(2)

def get_random_browser_headers() -> Dict[str, str]:
    """Returns a realistic, synchronized modern browser fingerprint."""
    profile = random.choice(BROWSER_PROFILES).copy()
    return profile

async def human_jitter_delay(min_sec: float = 1.2, max_sec: float = 2.8):
    """
    Simulates human pacing and browser reading timestops.
    Adds randomized Gaussian micro-variations to prevent rigid robotic intervals.
    """
    base_delay = random.uniform(min_sec, max_sec)
    jitter = random.gauss(0, 0.15)
    total_delay = max(0.4, base_delay + jitter)
    await asyncio.sleep(total_delay)

def get_scrape_semaphore() -> asyncio.Semaphore:
    """Returns the polite concurrency semaphore."""
    return _SCRAPE_SEMAPHORE
